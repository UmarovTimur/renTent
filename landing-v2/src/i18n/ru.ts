function plural(n: number, one: string, few: string, many: string) {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}

/** "1 сутки", "2 суток", "21 сутки", "1,5 суток" */
const formatDays = (n: number) =>
  Number.isInteger(n) ? `${n} ${plural(n, "сутки", "суток", "суток")}` : `${String(n).replace(".", ",")} суток`;

/** "1 час", "2 часа", "5 часов" */
const formatHours = (n: number) => `${n} ${plural(n, "час", "часа", "часов")}`;

